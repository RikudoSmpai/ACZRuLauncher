"""module/patches.json -> module/src/patches_gen.h (C table for the module).

    python module/tools/gen_header.py            write the header
    python module/tools/gen_header.py --check    exit 1 if the committed header is stale

Only the standard library. The header is committed, so building the module needs only MSVC.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'patches.json')
DST = os.path.join(ROOT, 'src', 'patches_gen.h')


def fail(msg):
    raise SystemExit('patches.json: ' + msg)


def build():
    doc = json.load(open(SRC, encoding='utf-8'))
    if doc.get('format') != 'acz-exe-strings/3':
        fail('format')
    exe = doc['exe']
    groups = doc['groups']
    gnames = sorted(groups)
    rd0, rdn = int(exe['rdata_rva'], 16), int(exe['rdata_vsize'], 16)
    out = ['/* GENERATED by module/tools/gen_header.py from module/patches.json - do not edit. */',
           '#pragma once',
           '#include "patch.h"',
           '',
           '#define ACZ_EXE_TIMESTAMP     0x%08xu' % int(exe['timestamp'], 16),
           '#define ACZ_EXE_SIZE_OF_IMAGE 0x%08xu' % int(exe['size_of_image'], 16),
           '#define ACZ_RDATA_RVA         0x%08xu' % rd0,
           '#define ACZ_RDATA_VSIZE       0x%08xu' % rdn,
           '']
    for i, g in enumerate(gnames):
        out.append('#define ACZ_GROUP_%s %d   /* %s; enabled in release: %s */' %
                   (g.upper(), i, groups[g].get('note', ''), 'yes' if groups[g]['enabled'] else 'no'))
    # one sha256 for the whole table: a hash per group (or per string) of a few short slots could be
    # brute-forced back to the English text
    for g in gnames:
        if 'sha256' in groups[g]: fail('group %s: sha256 per group is not allowed (one hash for the whole table)' % g)
    try:
        table_sha = bytes.fromhex(doc.get('table_sha256', ''))
    except ValueError:
        table_sha = b''
    if len(table_sha) != 32: fail('table_sha256')
    out.append('static const char *const acz_group_names[] = { %s };' % ', '.join('"%s"' % g for g in gnames))
    out.append('#define ACZ_GROUP_COUNT %d' % len(gnames))
    out.append('static const int acz_group_enabled[] = { %s };' %
               ', '.join('1' if groups[g]['enabled'] else 'ACZ_PROBE_BUILD' for g in gnames))
    out.append('static const unsigned char acz_table_sha256[32] = { %s };' % ', '.join('0x%02x' % c for c in table_sha))
    out.append('')
    seen = []
    rows = []
    for k, p in enumerate(doc['patches']):
        rva, n, slot = int(p['rva'], 16), int(p['len']), int(p['slot'])
        new = bytes.fromhex(p['bytes'])
        if 'sha256' in p: fail('%s: per-string sha256 is not allowed (one hash for the whole table)' % p['id'])
        if p['group'] not in groups: fail('%s: unknown group' % p['id'])
        if not (n < slot and rd0 <= rva and rva + slot <= rd0 + rdn): fail('%s: slot outside .rdata' % p['id'])
        # write rule: exactly the object [0, L+1); text <= L+1 bytes, zero padding after it
        if len(new) != n + 1: fail('%s: bytes must be L+1 = %d long' % (p['id'], n + 1))
        body = new.rstrip(b'\0')
        if b'\0' in body: fail('%s: NUL inside the new text' % p['id'])
        if len(body) > n + 1: fail('%s: new text longer than L+1' % p['id'])
        if len(body) == n + 1 and slot < n + 2: fail('%s: text of L+1 bytes needs a zero after the object' % p['id'])
        if any(c < 0x20 or c > 0x7e for c in body): fail('%s: non-ASCII code' % p['id'])
        for a, b in seen:
            if rva < b and a < rva + slot: fail('%s: overlaps another slot' % p['id'])
        seen.append((rva, rva + slot))
        out.append('static const unsigned char acz_new_%d[%d] = { %s };  /* %s: %s */' %
                   (k, n + 1, ', '.join('0x%02x' % c for c in new), p['id'], p['ru']))
        rows.append('    { 0x%06xu, %2d, %2d, ACZ_GROUP_%s, acz_new_%d },' %
                    (rva, n, slot, p['group'].upper(), k))
    out.append('')
    out.append('static const acz_patch acz_patches[] = {')
    out += rows
    out.append('};')
    out.append('#define ACZ_PATCH_COUNT %d' % len(rows))
    # LF-normalised, so a CRLF checkout (core.autocrlf) does not make the header look stale
    out.append('/* source sha256: %s */' % hashlib.sha256(open(SRC, 'rb').read().replace(b'\r\n', b'\n')).hexdigest())
    return '\n'.join(out) + '\n'


def main():
    text = build()
    if '--check' in sys.argv:
        cur = open(DST, encoding='utf-8').read() if os.path.exists(DST) else ''
        if cur != text:
            print('patches_gen.h is stale: run python module/tools/gen_header.py')
            return 1
        print('patches_gen.h is up to date')
        return 0
    with open(DST, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', DST)
    return 0


if __name__ == '__main__':
    sys.exit(main())
